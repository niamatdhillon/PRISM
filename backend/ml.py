"""Reproducible workload-classification workflow (scikit-learn).

Target : session-level raw NASA-TLX >= TLX_THRESHOLD ("high perceived workload"), 0/1.
Split  : participant-grouped hold-out (GroupShuffleSplit) -- a participant never appears in both train and test.
Models : majority-class baseline, standardised logistic regression (transparent), random forest.
Features are behavioural (+ optionally design conditions). The six TLX items and post-task stress are
excluded because they define / co-occur with the label (leakage).
"""
import hashlib
import json
from typing import Dict, List, Optional

import numpy as np
from sklearn.base import clone
from sklearn.dummy import DummyClassifier
from sklearn.ensemble import RandomForestClassifier
from sklearn.impute import SimpleImputer
from sklearn.inspection import permutation_importance
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import (accuracy_score, balanced_accuracy_score, confusion_matrix, f1_score, precision_score,
                             recall_score, roc_auc_score)
from sklearn.model_selection import GroupKFold, GroupShuffleSplit
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler

from . import analytics, synthetic

TLX_THRESHOLD = 50.0
SEED = 42
MIN_REAL = {"sessions": 30, "participants": 10, "minority": 8}
BEHAVIOUR = ["mean_rt_ms", "rt_sd_ms", "accuracy", "error_rate", "timeouts", "arithmetic_accuracy", "device_phone", "device_tablet"]
CONDITION = ["complexity", "movement", "distraction", "audio_enabled"]
FEATURE_SETS = {"behaviour_only": BEHAVIOUR, "behaviour_plus_condition": BEHAVIOUR + CONDITION}
_cache: Dict[str, Dict] = {}


def feature_row(m: Dict) -> Dict:
    return {**{k: m.get(k) for k in ["mean_rt_ms", "rt_sd_ms", "accuracy", "error_rate", "timeouts", "arithmetic_accuracy"]},
            "device_phone": 1.0 if m.get("device") == "phone" else 0.0, "device_tablet": 1.0 if m.get("device") == "tablet" else 0.0,
            "complexity": m.get("complexity"), "movement": float(bool(m.get("movement"))),
            "distraction": float(bool(m.get("distraction"))), "audio_enabled": float(bool(m.get("audio_enabled")))}


def build_dataset(records: List[dict]):
    rows = [analytics.session_metrics(r) for r in analytics.parse(records)]
    rows = [r for r in rows if r["completed"] and r["tlx_global"] is not None]
    X = [feature_row(r) for r in rows]
    y = np.array([int(r["tlx_global"] >= TLX_THRESHOLD) for r in rows])
    g = np.array([r["participant_id"] for r in rows])
    return X, y, g


def _mat(X, cols):
    return np.array([[np.nan if x[c] is None else float(x[c]) for c in cols] for x in X], dtype=float)


def _models():
    imp = lambda: SimpleImputer(strategy="median")  # noqa: E731
    return {
        "baseline_majority": DummyClassifier(strategy="most_frequent"),
        "logistic_regression": make_pipeline(imp(), StandardScaler(), LogisticRegression(class_weight="balanced", max_iter=2000)),
        "random_forest": make_pipeline(imp(), RandomForestClassifier(n_estimators=100, max_depth=5, min_samples_leaf=3,
                                                                    class_weight="balanced_subsample", random_state=0, n_jobs=1)),
    }


def _split(y, g):
    for s in range(SEED, SEED + 200):
        tr, te = next(GroupShuffleSplit(n_splits=1, test_size=0.25, random_state=s).split(np.zeros(len(y)), y, g))
        if len(set(y[tr])) == 2 and len(set(y[te])) == 2 and min(np.bincount(y[te])) >= 3:
            return tr, te, s
    return None, None, None


def _metrics(model, Xte, yte):
    pred = model.predict(Xte)
    out = {"accuracy": accuracy_score(yte, pred), "balanced_accuracy": balanced_accuracy_score(yte, pred),
           "precision": precision_score(yte, pred, zero_division=0), "recall": recall_score(yte, pred, zero_division=0),
           "f1": f1_score(yte, pred, zero_division=0), "confusion_matrix": confusion_matrix(yte, pred, labels=[0, 1]).tolist()}
    if hasattr(model, "predict_proba") and len(set(yte)) == 2:
        out["roc_auc"] = roc_auc_score(yte, model.predict_proba(Xte)[:, 1])
    return {k: (round(float(v), 3) if not isinstance(v, list) else v) for k, v in out.items()}


def evaluate(records: List[dict], source: str) -> Dict:
    key = source + hashlib.md5(json.dumps([r.get("session_id") for r in records]).encode()).hexdigest()
    if key in _cache:
        return _cache[key]
    X, y, g = build_dataset(records)
    n, n_part = len(y), len(set(g))
    counts = {"low": int((y == 0).sum()), "high": int((y == 1).sum())}
    provenance = ("SYNTHETIC demonstration data generated by backend/synthetic.py with documented assumptions. Metrics show only that the pipeline "
                  "can recover those assumptions; they are NOT evidence about human behaviour." if source == "synthetic" else
                  "Real participant sessions recorded by this PRISM installation with informed consent (self-selected, small, uncontrolled device/environment).")
    base = {"source": source, "target": f"High perceived workload: raw NASA-TLX >= {TLX_THRESHOLD:.0f} (arbitrary documented cut-off; not a clinical threshold)",
            "n_sessions": n, "n_participants": n_part, "class_counts": counts, "provenance": provenance,
            "excluded_features": ["tlx_* items (define the label)", "post_stress (co-outcome measured after the task)"]}
    if source == "participant" and (n < MIN_REAL["sessions"] or n_part < MIN_REAL["participants"] or min(counts.values()) < MIN_REAL["minority"]):
        res = {**base, "status": "insufficient_data", "label": "UNEVALUATED -- not enough real data",
               "message": f"Supervised evaluation needs >= {MIN_REAL['sessions']} completed sessions from >= {MIN_REAL['participants']} participants with >= {MIN_REAL['minority']} in each class. "
                          f"Currently {n} sessions / {n_part} participants / classes {counts}. No accuracy is reported because none can be validly estimated."}
        return res  # not cached: data changes as the user participates
    if n < 12 or min(counts.values()) < 3:
        return {**base, "status": "insufficient_data", "label": "UNEVALUATED", "message": "Too few sessions or a single class present."}
    tr, te, seed = _split(y, g)
    if tr is None:
        return {**base, "status": "insufficient_data", "label": "UNEVALUATED", "message": "Could not form a participant-grouped split with both classes in train and test."}
    results = {}
    for fs, cols in FEATURE_SETS.items():
        M = _mat(X, cols)
        fs_res = {"features": cols, "models": {}}
        for name, mdl in _models().items():
            m = clone(mdl).fit(M[tr], y[tr])
            met = _metrics(m, M[te], y[te])
            cv = []
            ytr, gtr = y[tr], g[tr]
            for a, b in GroupKFold(n_splits=min(5, len(set(gtr)))).split(M[tr], ytr, gtr):
                if len(set(ytr[a])) < 2:
                    continue
                cv.append(f1_score(ytr[b], clone(mdl).fit(M[tr][a], ytr[a]).predict(M[tr][b]), zero_division=0))
            met["cv_f1_train_mean"] = round(float(np.mean(cv)), 3) if cv else None
            met["cv_f1_train_sd"] = round(float(np.std(cv)), 3) if cv else None
            fs_res["models"][name] = met
            if name == "logistic_regression":
                coef = m[-1].coef_[0]
                fs_res["logistic_coefficients_standardised"] = sorted([{"feature": c, "coef": round(float(v), 3)} for c, v in zip(cols, coef)], key=lambda d: -abs(d["coef"]))
            if name == "random_forest":
                pi = permutation_importance(m, M[te], y[te], n_repeats=10, random_state=0, scoring="balanced_accuracy")
                fs_res["rf_permutation_importance_test"] = sorted([{"feature": c, "mean": round(float(a), 3), "sd": round(float(b), 3)} for c, a, b in zip(cols, pi.importances_mean, pi.importances_std)], key=lambda d: -d["mean"])
        results[fs] = fs_res
    yte = y[te]
    res = {**base, "status": "ok",
           "label": "TRAINED MODEL on SYNTHETIC DEMO DATA (not evidence about people)" if source == "synthetic" else "TRAINED MODEL on participant data (small-sample, exploratory)",
           "split": {"method": "GroupShuffleSplit by participant, test 25%", "seed": int(seed), "n_train_sessions": int(len(tr)), "n_test_sessions": int(len(te)),
                     "n_train_participants": int(len(set(g[tr]))), "n_test_participants": int(len(set(g[te]))),
                     "test_class_counts": {"low": int((yte == 0).sum()), "high": int((yte == 1).sum())}},
           "feature_sets": results, "primary_feature_set": "behaviour_only", "primary_model": "logistic_regression",
           "limitations": ["Single hold-out split: test metrics have wide uncertainty at this sample size (see cv_f1_train_sd).",
                           "The label is a self-report threshold, not an objective workload measurement.",
                           "Not a clinical or diagnostic tool; no claim is made about stress or cognitive health."]}
    _cache[key] = res
    return res


def predict(features: Dict, records: Optional[List[dict]] = None) -> Dict:
    """Illustrative prediction from the logistic model trained on the synthetic demo set (behaviour-only features)."""
    if "pred_model" not in _cache:
        recs = synthetic.generate()
        X, y, g = build_dataset(recs)
        M = _mat(X, BEHAVIOUR)
        _cache["pred_model"] = _models()["logistic_regression"].fit(M, y)  # trained on all synthetic rows: for illustration only
    x = np.array([[np.nan if features.get(c) is None else float(features[c]) for c in BEHAVIOUR]])
    p = float(_cache["pred_model"].predict_proba(x)[0, 1])
    return {"probability_high_workload": round(p, 3), "label": "ILLUSTRATIVE PREDICTION from a demo model trained on synthetic data -- not a measurement of any person",
            "features_used": BEHAVIOUR}
